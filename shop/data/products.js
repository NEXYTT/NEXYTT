/** Effective price of a product in a given variant. */
export function variantPrice(product, variantId) {
  const variant = product.variants?.find((v) => v.id === variantId);
  return product.price + (variant?.priceDelta ?? 0);
}

export const variantOf = (product, variantId) =>
  product.variants?.find((v) => v.id === variantId) ?? product.variants?.[0] ?? null;
